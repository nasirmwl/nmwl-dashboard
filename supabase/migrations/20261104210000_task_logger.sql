-- Task logger: moves "Today's log" from browser localStorage into Supabase.
--
-- Unlike the older tables, these are locked down from day one: RLS is on and
-- every row belongs to the signed-in user (auth.uid()). The anon key alone
-- cannot read or write anything here.
--
-- Minutes are an append-only ledger (one row per +15 / -5 / timer run), so
-- two devices logging at the same time can never overwrite each other, and
-- daily totals are just sum(minutes) grouped by day.

create table public.task_logger_tasks (
  id text primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null check (char_length(btrim(name)) between 1 and 80),
  created_at timestamptz not null default now()
);

create unique index task_logger_tasks_user_name_key
  on public.task_logger_tasks (user_id, lower(name));

create table public.task_logger_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  task_id text not null references public.task_logger_tasks (id) on delete cascade,
  -- Local calendar day of the person logging (the client's midnight).
  day date not null,
  -- Signed: negative rows correct mistakes.
  minutes integer not null check (minutes between -1440 and 1440 and minutes <> 0),
  source text not null default 'manual' check (source in ('manual', 'timer', 'import')),
  -- Makes the one-time localStorage import safe to retry.
  import_key text unique,
  created_at timestamptz not null default now()
);

create index task_logger_entries_user_day_idx
  on public.task_logger_entries (user_id, day);

-- At most one running timer per user, shared across devices.
create table public.task_logger_timers (
  user_id uuid primary key default auth.uid() references auth.users (id) on delete cascade,
  task_id text not null references public.task_logger_tasks (id) on delete cascade,
  started_at timestamptz not null default now()
);

alter table public.task_logger_tasks enable row level security;
alter table public.task_logger_entries enable row level security;
alter table public.task_logger_timers enable row level security;

create policy "own tasks" on public.task_logger_tasks
  for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

create policy "own entries" on public.task_logger_entries
  for all to authenticated
  using (user_id = (select auth.uid()))
  with check (
    user_id = (select auth.uid())
    and exists (
      select 1 from public.task_logger_tasks t
      where t.id = task_id and t.user_id = (select auth.uid())
    )
  );

create policy "own timer" on public.task_logger_timers
  for all to authenticated
  using (user_id = (select auth.uid()))
  with check (
    user_id = (select auth.uid())
    and exists (
      select 1 from public.task_logger_tasks t
      where t.id = task_id and t.user_id = (select auth.uid())
    )
  );

revoke all on public.task_logger_tasks, public.task_logger_entries, public.task_logger_timers from anon;

-- Start / stop / switch the timer in one transaction.
--
-- Whatever timer was running is stopped and credited, split at each local
-- midnight (p_tz_offset_minutes = JS Date#getTimezoneOffset(), e.g. -240 for
-- UTC+4). If p_task_id is a different task than the one that was running, a
-- new timer starts on it; the same task (or null) just stops.
create or replace function public.task_logger_toggle_timer(
  p_task_id text,
  p_tz_offset_minutes integer
)
returns table (task_id text, started_at timestamptz)
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_now timestamptz := now();
  v_off interval := make_interval(mins => p_tz_offset_minutes);
  v_old_task text;
  v_old_start timestamptz;
begin
  if v_uid is null then
    raise exception 'not authenticated';
  end if;

  delete from public.task_logger_timers t
  where t.user_id = v_uid
  returning t.task_id, t.started_at into v_old_task, v_old_start;

  if v_old_task is not null then
    insert into public.task_logger_entries (user_id, task_id, day, minutes, source)
    select v_uid, v_old_task, seg.day, seg.minutes, 'timer'
    from (
      select
        d::date as day,
        round(extract(epoch from (
          least(v_now, ((d + interval '1 day') + v_off) at time zone 'UTC')
          - greatest(v_old_start, (d + v_off) at time zone 'UTC')
        )) / 60)::integer as minutes
      from generate_series(
        date_trunc('day', (v_old_start at time zone 'UTC') - v_off),
        date_trunc('day', (v_now at time zone 'UTC') - v_off),
        interval '1 day'
      ) as d
    ) seg
    where seg.minutes > 0;
  end if;

  if p_task_id is not null and p_task_id is distinct from v_old_task then
    insert into public.task_logger_timers (user_id, task_id, started_at)
    values (v_uid, p_task_id, v_now);
    return query select p_task_id, v_now;
  end if;
end;
$$;

revoke execute on function public.task_logger_toggle_timer(text, integer) from public, anon;
grant execute on function public.task_logger_toggle_timer(text, integer) to authenticated;

-- Live sync between phone and laptop.
alter publication supabase_realtime
  add table public.task_logger_tasks, public.task_logger_entries, public.task_logger_timers;
